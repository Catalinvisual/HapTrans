  doc.rect(14, y, boxW + 5, 50, 'F'); // clear old
  doc.roundedRect(14, y, boxW + 5, finalLeftH, 2, 2, 'S');
  // Redraw header
  doc.setFont('helvetica', 'bold');
  setCol(colors.orange);
  doc.text(t.transportDetails, 24, y + 6);
  setFill(colors.orange);
  doc.circle(18, y + 5, 1.5, 'F');
  // Re-run render
  ly = y + 14;
  if (invoice.trip) {
    if (invoice.trip.pickupAddress || invoice.trip.dropoffAddress) {
      renderDetailRow(t.route, safeText(`${invoice.trip.pickupAddress || ''} - ${invoice.trip.dropoffAddress || ''}`));
    }
    renderDetailRow(t.pickupDate, safeText(fmtDate(invoice.trip.pickupDate)));
    if (invoice.trip.loadingReference) renderDetailRow(t.loadingRef, safeText(invoice.trip.loadingReference));
    renderDetailRow(t.deliveryDate, safeText(fmtDate(invoice.trip.dropoffDate)));
    if (invoice.trip.unloadingReference) renderDetailRow(t.unloadingRef, safeText(invoice.trip.unloadingReference));
    
    const cargo = [];
    if (invoice.trip.pallets) cargo.push(`${invoice.trip.pallets} pallets`);
    if (invoice.trip.weightKg) cargo.push(`${invoice.trip.weightKg} kg`);
    if (invoice.trip.volumeCbm) cargo.push(`${invoice.trip.volumeCbm} m3`);
    if (cargo.length > 0) renderDetailRow(t.cargo, safeText(cargo.join(', ')));
  }


  // Right Box: SUMMARY
  let ry = y;
  const rightX = 112;
  const rightW = 84;
  
  // Header
  setFill(colors.darkBlue);
  doc.roundedRect(rightX, ry, rightW, 8, 1, 1, 'F');
  doc.setFont('helvetica', 'bold');
  setCol([255, 255, 255]);
  doc.text(t.summary, rightX + 4, ry + 5.5);
  
  ry += 16;
  
  let subtotal = Number(invoice.subtotal) || itemsSubtotal;
  let vatLabel = `${t.vat} ${invoice.vatPercent || 19}%`;
  let vatAmt = Number(invoice.vatAmount) || (subtotal * (invoice.vatPercent || 19)) / 100;

  if (invoice.vatType === 'REVERSE_CHARGE') {
    vatLabel = `${t.vat} 0% (Reverse Charge)`;
    vatAmt = 0;
  } else if (invoice.vatType === 'EXEMPT') {
    vatLabel = `${t.vat} 0% (Exempt)`;
    vatAmt = 0;
  }
  
  const finalTotal = subtotal + vatAmt;

  doc.setFont('helvetica', 'normal');
  setCol(colors.textDark);
  doc.text(t.subtotal, rightX + 4, ry);
  doc.text(`EUR ${subtotal.toFixed(2)}`, rightX + rightW - 4, ry, { align: 'right' });
  
  ry += 8;
  doc.text(vatLabel, rightX + 4, ry);
  doc.text(`EUR ${vatAmt.toFixed(2)}`, rightX + rightW - 4, ry, { align: 'right' });

  ry += 6;
  setDraw(colors.border);
  doc.setLineWidth(0.5);
  doc.line(rightX, ry, rightX + rightW, ry);

  ry += 10;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  setCol(colors.darkBlue);
  doc.text(t.total, rightX + 4, ry);
  setCol(colors.orange);
  doc.text(`EUR ${finalTotal.toFixed(2)}`, rightX + rightW - 4, ry, { align: 'right' });

  ry += 8;
  // VAT Info Box
  setFill(colors.lightBlue);
  doc.roundedRect(rightX, ry, rightW, 16, 2, 2, 'F');
  setDraw(colors.darkBlue);
  doc.circle(rightX + 6, ry + 5, 2, 'S');
  doc.setFontSize(6);
  setCol(colors.darkBlue);
  doc.text('i', rightX + 5.5, ry + 6);
  
  doc.setFontSize(8);
  doc.setFont('helvetica', 'bold');
  doc.text(t.vatInfo, rightX + 10, ry + 6);
  
  doc.setFont('helvetica', 'normal');
  setCol(colors.textLight);
  doc.text(`The VAT rate applied is ${invoice.vatPercent || 19}%.`, rightX + 10, ry + 10);
  doc.text(t.vatInfoText, rightX + 10, ry + 14);

  // Enclose Summary in a box? The mockup shows a very light border around the whole summary area
  const summaryBoxH = ry + 16 - y;
  setDraw(colors.border);
  doc.roundedRect(rightX, y, rightW, summaryBoxH, 2, 2, 'S');

  y = Math.max(y + finalLeftH, y + summaryBoxH) + 8;

  // --- PAYMENT INFO ---
  setDraw(colors.border);
  doc.roundedRect(14, y, 182, 34, 2, 2, 'S');

  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  setCol(colors.orange);
  doc.text(t.paymentInfo, 24, y + 6);
  // Bank icon
  setFill(colors.orange);
  doc.rect(18, y + 4, 4, 3, 'F');
  doc.rect(19, y + 2.5, 2, 1, 'F');

  let py = y + 14;
  doc.setFont('helvetica', 'normal');
  setCol(colors.textLight);
  doc.text(`${t.bank}:`, 20, py); setCol(colors.textDark); doc.text(coBank, 45, py); py += 5;
  setCol(colors.textLight); doc.text(`${t.iban}:`, 20, py); setCol(colors.textDark); doc.text(coIban, 45, py); py += 5;
  setCol(colors.textLight); doc.text(`${t.bic}:`, 20, py); setCol(colors.textDark); doc.text(safeText(co.bic || 'INGBNL2A'), 45, py); py += 5;
  setCol(colors.textLight); doc.text(`${t.accHolder}:`, 20, py); setCol(colors.textDark); doc.text(coName, 45, py);

  // Late warning box
  setFill(colors.lightBlue);
  doc.roundedRect(100, y + 10, 90, 16, 2, 2, 'F');
  setDraw(colors.darkBlue);
  doc.circle(105, y + 15, 2, 'S');
  doc.setFontSize(6);
  doc.text('!', 104.5, y + 16);
  
  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  setCol(colors.textDark);
  doc.text(`${t.lateWarning} ${termsStr}`, 110, y + 16);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  setCol(colors.textLight);
  doc.text(t.lateWarningSub, 110, y + 21);

  // --- FOOTER ---
  doc.setFontSize(8);
  setCol(colors.textLight);
  const footY = 285;
  const fText = `${co.website || 'www.hapcargo.com'}   |   ${coEmail}   |   ${coPhone}`;
  doc.text(fText, 105, footY, { align: 'center' });
  
  doc.setFont('helvetica', 'italic');
  setCol(colors.darkBlue);
  doc.text(t.footer1, 105, footY + 4, { align: 'center' });

  return doc.output('datauristring');
