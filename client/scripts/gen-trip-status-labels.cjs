/* Generates client/src/lib/tripStatusLabels.ts from the driver app source.
   The mobile file is the single source of truth for status names, so the TMS
   never keeps a second, drifting translation of the same list. */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..', '..');
const dartPath = path.join(root, 'mobile', 'lib', 'utils', 'trip_status.dart');
const outPath = path.join(root, 'client', 'src', 'lib', 'tripStatusLabels.ts');

const src = fs.readFileSync(dartPath, 'utf8');
const LANGS = ['ro', 'en', 'nl', 'de', 'fr', 'es', 'pl'];

// The driver-facing operational table, nested per language.
const block = src.match(/_operationalLabels\s*=\s*\{([\s\S]*?)\n\};/);
if (!block) {
  console.error('Could not find _operationalLabels in trip_status.dart');
  process.exit(1);
}
const body = block[1];

const labels = {};
for (const lang of LANGS) {
  const re = new RegExp(`'${lang}'\\s*:\\s*\\{([\\s\\S]*?)\\n\\s*\\},`);
  const m = body.match(re);
  if (!m) continue;
  const map = {};
  const pairRe = /'([^']+)'\s*:\s*'((?:[^'\\]|\\.)*)'/g;
  let p;
  while ((p = pairRe.exec(m[1]))) map[p[1]] = p[2].replace(/\\'/g, "'");
  if (Object.keys(map).length) labels[lang] = map;
}

const order = Object.keys(labels.ro || labels.en || {});
if (!order.length) {
  console.error('No labels parsed.');
  process.exit(1);
}

const header = `// AUTO-GENERATED by client/scripts/gen-trip-status-labels.cjs
// Source of truth: mobile/lib/utils/trip_status.dart (driver app).
// Do not hand-edit: run \`node scripts/gen-trip-status-labels.cjs\` instead.

export type TripStatusLang = '${LANGS.join("' | '")}';

/** The driver-facing operational statuses, in the order the app shows them. */
export const TRIP_STATUS_ORDER = ${JSON.stringify(order, null, 2)} as const;

export type TripStatusCode = typeof TRIP_STATUS_ORDER[number];

/** Same wording the driver sees in the app, per language. */
export const TRIP_STATUS_LABELS: Record<TripStatusLang, Record<string, string>> = ${JSON.stringify(labels, null, 2)};

export function tripStatusLabel(status: string | null | undefined, lang: string): string {
  const code = String(status || '').toLowerCase();
  const table = TRIP_STATUS_LABELS[(lang as TripStatusLang)] || TRIP_STATUS_LABELS.en;
  return table[code] || TRIP_STATUS_LABELS.en[code] || code.replace(/_/g, ' ');
}
`;

fs.writeFileSync(outPath, header, 'utf8');
console.log(`wrote ${outPath}: ${order.length} statuses x ${Object.keys(labels).length} languages`);
