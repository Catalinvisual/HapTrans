/**
 * Shared i18n foundation (ADR-017).
 *
 * Exactly six languages: RO, EN, NL, PL, FR, ES.
 * English is the technical source and fallback language.
 * Resources are plain JSON-compatible objects shared by web, mobile, portals,
 * and server (PDFs/emails/notifications reuse these bundles).
 */
export const SUPPORTED_LOCALES = ['ro', 'en', 'nl', 'pl', 'fr', 'es'] as const;
export type Locale = (typeof SUPPORTED_LOCALES)[number];
export const DEFAULT_LOCALE: Locale = 'en';

export const LOCALE_META: Record<Locale, { label: string; native: string }> = {
  ro: { label: 'Romanian', native: 'Română' },
  en: { label: 'English', native: 'English' },
  nl: { label: 'Dutch', native: 'Nederlands' },
  pl: { label: 'Polish', native: 'Polski' },
  fr: { label: 'French', native: 'Français' },
  es: { label: 'Spanish', native: 'Español' },
};

export function isLocale(value: string): value is Locale {
  return (SUPPORTED_LOCALES as readonly string[]).includes(value);
}

