/**
 * Computes verifiable SHA-256 fingerprint of the seed dataset
 */
export function getCatalogChecksum(dataset: AdrSeedRecord[]): string {
  const json = JSON.stringify(dataset.map(d => ({ un: d.unNumber, cls: d.adrClass, pg: d.packingGroup, cat: d.transportCategory })));
  return crypto.createHash('sha256').update(json).digest('hex');
}
